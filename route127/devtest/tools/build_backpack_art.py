"""Build a deterministic portrait manifest from existing generated item images.

Original generation PNGs remain in generated_images. WebP is a format-only,
alpha-preserving conversion for lazy loading inside the Backpack preview.
"""
import json
import re
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
art = root / 'assets/items'
app = (root / 'app.js').read_text()
catalog = json.loads(re.search(r'const EQUIPMENT_CATALOG = (\[.*?\]);', app).group(1))
extra = json.loads((root / 'tools/backpack_art_extra_items.json').read_text())
entries = []
for definition in catalog + extra:
    ident = definition['id']
    png, webp = art / (ident + '.png'), art / (ident + '.webp')
    if png.exists() and (not webp.exists() or png.stat().st_mtime > webp.stat().st_mtime):
        with Image.open(png) as image:
            assert image.mode == 'RGBA' and image.getextrema()[3][0] == 0, ident + ': missing transparency'
            image.save(webp, format='WEBP', quality=88, method=4)
    if webp.exists():
        entries.append({'id': ident, 'name': definition['name'], 'type': definition['type'], 'file': webp.name})
manifest = '/* Explicit item identities; generated by tools/build_backpack_art.py. */\n'
manifest += 'globalThis.Route127ItemArtworkManifest=Object.freeze(' + json.dumps({'version': '20261124', 'entries': entries}, indent=2) + ');\n'
(root / 'runtime/backpack_item_art_manifest.js').write_text(manifest)
print(f'{len(entries)}/{len(catalog) + len(extra)} item portraits registered')
